// Writes prisma/sqlite/schema.prisma: the SQL Server schema converted for SQLite.
// Used by the Vercel demo deployment, which ships a pre-seeded SQLite file instead of a database server.
const fs = require('fs');
const path = require('path');

const source = fs.readFileSync(path.join(__dirname, '..', 'prisma', 'schema.prisma'), 'utf8');

const schema = source
  .replace(/provider\s*=\s*"sqlserver"/, 'provider = "sqlite"')
  .replace(/provider\s*=\s*"prisma-client-js"/, 'provider      = "prisma-client-js"\n  binaryTargets = ["native", "rhel-openssl-3.0.x"]')
  .replace(/\s@db\.\w+(\([^)]*\))?/g, '');

if (schema.includes('@db.')) throw new Error('Unconverted @db attribute left in the SQLite schema');

const outDir = path.join(__dirname, '..', 'prisma', 'sqlite');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'schema.prisma'), `// Generated by scripts/make-sqlite-schema.cjs. Do not edit.\n${schema}`);
console.log('Wrote prisma/sqlite/schema.prisma');
